def build_date(arg):
    if arg:
        datetime.date.fromisoformat(arg)
        return arg
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch:
        return datetime.datetime.fromtimestamp(int(epoch), datetime.timezone.utc).date().isoformat()
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def write_outputs(page, scripts, out, scripts_dir):
    """Write the page and the scripts folder; the folder holds exactly the build's scripts."""
    out = Path(out)
    scripts_dir = Path(scripts_dir)
    scripts_dir.mkdir(parents=True, exist_ok=True)
    wanted = set(scripts)
    for old in sorted(scripts_dir.rglob("*"), reverse=True):
        rel = old.relative_to(scripts_dir).as_posix()
        if old.is_file() and rel not in wanted:
            old.unlink()
        elif old.is_dir() and not any(old.iterdir()):
            old.rmdir()
    for name, (data, executable) in sorted(scripts.items()):
        target = scripts_dir / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
        target.chmod(0o755 if executable else 0o644)
    out.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=out.parent, prefix=".local-setup-", suffix=".html")
    with os.fdopen(fd, "wb") as fh:
        fh.write(page.encode("utf-8"))
    os.replace(tmp, out)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build docs/local-setup/index.html from steps.json.")
    ap.add_argument("--steps", default=str(STEPS))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--scripts", default=str(SCRIPTS))
    ap.add_argument("--date", help="build date, YYYY-MM-DD")
    ap.add_argument("--sync-site", action="store_true",
                    help="write site/tokens.css and site/designs.js from design/website without comments, then build")
    ap.add_argument("--make-placeholders", action="store_true",
                    help="write a marked placeholder PNG for every plate that has no file yet, then stop")
    args = ap.parse_args(argv)
    try:
        if args.make_placeholders:
            doc = json.loads(Path(args.steps).read_text(encoding="utf-8"))
            for made in make_placeholders(doc):
                print(f"placeholder {made}")
            return 0
        if args.sync_site:
            for made in sync_site():
                print(f"synced {made}")
        doc = load(args.steps)
        date = build_date(args.date)
        scripts = scripts_for(doc, date)
        page = stamp(render(doc, date, scripts), doc)
        write_outputs(page, scripts, args.out, args.scripts)
    except BuildError as err:
        print(f"build_local_setup: {err}", file=sys.stderr)
        return 1
    size = Path(args.out).stat().st_size
    print(f"wrote {args.out} ({size:,} bytes) and {len(scripts)} scripts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
