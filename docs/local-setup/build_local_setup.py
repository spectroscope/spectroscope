# ---------------------------------------------------------------- schema

def validate(value, schema, root=None, where="$"):
    """The subset of JSON Schema steps.schema.json uses. Returns a list of errors."""
    root = root if root is not None else schema
    errors = []
    if "$ref" in schema:
        ref = schema["$ref"]
        target = root
        for part in ref.lstrip("#/").split("/"):
            target = target[part]
        return validate(value, target, root, where)
    if "anyOf" in schema:
        if not any(not validate(value, s, root, where) for s in schema["anyOf"]):
            errors.append(f"{where}: matches none of the allowed shapes")
        return errors
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{where}: {value!r} is not one of {schema['enum']}")
    kind = schema.get("type")
    types = {"object": dict, "array": list, "string": str, "integer": int, "boolean": bool, "null": type(None)}
    if kind:
        ok = isinstance(value, types[kind]) and not (kind == "integer" and isinstance(value, bool))
        if not ok:
            return errors + [f"{where}: expected {kind}"]
    if isinstance(value, str) and "pattern" in schema and not re.search(schema["pattern"], value):
        errors.append(f"{where}: {value!r} does not match {schema['pattern']}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{where}: needs at least {schema['minItems']} items")
        if "items" in schema:
            for i, item in enumerate(value):
                errors += validate(item, schema["items"], root, f"{where}[{i}]")
    if isinstance(value, dict):
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{where}: missing {key}")
        props = schema.get("properties", {})
        names = schema.get("propertyNames")
        for key, item in value.items():
            if names and not re.search(names.get("pattern", ""), key):
                errors.append(f"{where}: key {key!r} does not match {names['pattern']}")
            if key in props:
                errors += validate(item, props[key], root, f"{where}.{key}")
            elif schema.get("additionalProperties") is False:
                errors.append(f"{where}: unexpected key {key}")
            elif isinstance(schema.get("additionalProperties"), dict):
                errors += validate(item, schema["additionalProperties"], root, f"{where}.{key}")
    return errors


def sources_of(value):
    return value if isinstance(value, list) else [value]


def check_sources(doc):
    """Every printed line names a source, and every source resolves."""
    problems = []

    def need(owner, value):
        if value is None:
            problems.append(f"{owner}: no source")
            return
        for src in sources_of(value):
            if src.startswith("S"):
                if src not in doc["sources"]:
                    problems.append(f"{owner}: source {src} is not in the sources table")
            elif src.startswith("P:"):
                path, _, needle = src[2:].partition("::")
                if not (REPO / path).is_file():
                    problems.append(f"{owner}: source {src} names no file in the repository")
                elif needle and needle not in (REPO / path).read_text(encoding="utf-8", errors="replace"):
                    problems.append(f"{owner}: {path} does not contain {needle!r}")
                elif len(needle) > NEEDLE_MAX:
                    problems.append(f"{owner}: the cited text of {src} is longer than {NEEDLE_MAX} characters")
            else:
                problems.append(f"{owner}: source {src!r} is neither an S row nor P:<path>")

    for step in doc["steps"]:
        sid = step.get("id", "?")
        for platform, commands in step.get("commands", {}).items():
            for i, c in enumerate(commands):
                need(f"step {sid} {platform} command {i + 1} ({c.get('text', '')[:40]!r})", c.get("source"))
        for platform, lines in step.get("vendor", {}).items():
            for i, v in enumerate(lines):
                need(f"step {sid} {platform} vendor line {i + 1}", v.get("source"))
        for group in ("notes", "links"):
            for platform, items in step.get(group, {}).items():
                for i, item in enumerate(items):
                    need(f"step {sid} {platform} {group[:-1]} {i + 1}", item.get("source"))
        for platform, check in step.get("check", {}).items():
            if check.get("kind") != "none":
                need(f"step {sid} {platform} check", check.get("source"))
        for i, size in enumerate(step.get("size", [])):
            need(f"step {sid} size {i + 1}", size.get("source"))
        if "address" in step:
            need(f"step {sid} address", step["address"].get("source"))
        if "notNeeded" in step:
            need(f"step {sid} notNeeded", step["notNeeded"].get("source"))
    if "scope" in doc["page"]:
        need("page scope", doc["page"]["scope"].get("source"))
    for key, item in doc["page"].get("needs", {}).items():
        for platform, entry in item["platforms"].items():
            need(f"page needs {key} {platform}", entry.get("source"))
    return problems


def check_shape(doc):
    problems = []
    levels = {lv["id"] for lv in doc["levels"]}
    for step in doc["steps"]:
        sid = step["id"]
        if step["level"] not in levels:
            problems.append(f"step {sid}: level {step['level']} does not exist")
        if not sid.startswith(f"{step['level']}."):
            problems.append(f"step {sid}: id does not belong to level {step['level']}")
        for platform in step["commands"]:
            if platform not in step["platforms"]:
                problems.append(f"step {sid}: commands for {platform}, which the step does not list")
        if step["script"] == "generate" and not step["commands"]:
            problems.append(f"step {sid}: script generate, but there are no commands")
        missing = [p for p in PLATFORMS if p not in step["platforms"]]
        if missing:
            for group in ("check", "notes", "links"):
                if "all" in step.get(group, {}):
                    problems.append(f"step {sid}: {group} all on a step that does not cover {' and '.join(missing)}")
                for platform in missing:
                    if platform in step.get(group, {}):
                        problems.append(f"step {sid}: {group} for {platform}, which the step does not cover")
        for i, size in enumerate(step["size"]):
            for platform in size["platforms"]:
                if platform not in step["platforms"]:
                    problems.append(f"step {sid}: size {i + 1} is for {platform}, which the step does not cover")
        if isinstance(step["script"], dict):
            for copy in step["script"]["copy"]:
                if not (REPO / copy["from"]).is_file():
                    problems.append(f"step {sid}: script source {copy['from']} does not exist")
        for platform, commands in step["commands"].items():
            installed = set()
            for c in commands:
                lines = c["text"].splitlines()
                wanted = set()
                if any(line.startswith("brew ") for line in lines):
                    wanted.add("homebrew")
                if any(line.startswith("git clone") for line in lines):
                    wanted.add("git")
                if any(line.startswith("sudo apt install docker-ce") for line in lines):
                    wanted.add("docker-repo")
                if any(line.startswith("cmake ") for line in lines):
                    wanted.add("build-tools")
                if any(line.startswith("ollama ") for line in lines) and "ollama" not in installed:
                    wanted.add("ollama")
                if any(line.startswith("brew install ollama") for line in lines):
                    installed.add("ollama")
                for missing in sorted(wanted - set(c.get("needs", []))):
                    problems.append(f"step {sid} {platform} {c['text'][:40]!r}: needs {missing} and does not say so")
                for name in c.get("needs", []):
                    if platform not in doc["page"]["needs"].get(name, {}).get("platforms", {}):
                        problems.append(f"step {sid} {platform}: needs {name}, which page.needs does not explain on {platform}")
        for name in step["shots"]:
            if name not in doc["plates"]:
                problems.append(f"step {sid}: plate {name} has no caption in plates")
            for design, folder in SHOTS.items():
                if not (folder / f"{name}.png").is_file():
                    problems.append(f"step {sid}: missing plate {folder.name}/{name}.png")
    return problems


def load(path):
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        raise BuildError(f"{path}: {err}")
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    problems = validate(doc, schema)
    if problems:
        raise BuildError("steps.json breaks its schema:\n  " + "\n  ".join(problems))
    problems = check_sources(doc) + check_shape(doc)
    if problems:
        raise BuildError("refusing to build:\n  " + "\n  ".join(problems))
    return doc


# ---------------------------------------------------------------- scripts

def script_name(step_id, platform):
    return f"{platform}-step-{step_id.replace('.', '-')}.sh"


def split_script(text):
    """(preamble, body) of a generated script; the preamble ends at the first blank line."""
    cut = text.index("\n\n")
    return text[: cut + 1], text[cut + 2:]


def needs_comment(doc, commands):
    """The header line that names what a script's lines need first, or nothing."""
    names = []
    for c in commands:
        for n in c.get("needs", []):
            name = doc["page"]["needs"][n]["name"]
            if name not in names:
                names.append(name)
    if not names:
        return ""
    return (f"# Needs first: {' and '.join(names)}. The page explains "
            f"{'it' if len(names) == 1 else 'them'} under \"before you start\".\n")


def scripts_for(doc, date):
    """name -> (bytes, executable) for every script the page links."""
    out = {}
    for step in doc["steps"]:
        if step["script"] == "generate":
            for platform, commands in step["commands"].items():
                kept = [c for c in commands if c.get("script", True)]
                lines = [c["text"] for c in kept]
                if not lines:
                    continue
                name = script_name(step["id"], platform)
                pre = SCRIPT_PREAMBLE.format(name=name, step=step["id"],
                                             platform=doc["platformNames"][platform], date=date,
                                             needs=needs_comment(doc, kept))
                out[name] = ((pre + "\n".join(lines) + "\n").encode(), True)
        elif isinstance(step["script"], dict):
            for copy in step["script"]["copy"]:
                src = REPO / copy["from"]
                out[copy["to"]] = (src.read_bytes(), os.access(src, os.X_OK))
    return out


# ---------------------------------------------------------------- plates

def is_placeholder(png):
    return PLACEHOLDER_MARK in png.read_bytes()


def webp_bytes(png):
    if not shutil.which("cwebp"):
        raise BuildError("cwebp not found; install it with `brew install webp` (plates go in as lossless WebP)")
    st = png.stat()
    WEBP_CACHE.mkdir(exist_ok=True)
    cached = WEBP_CACHE / f"{png.parent.name}--{png.stem}--{int(st.st_mtime)}-{st.st_size}.webp"
    if not cached.exists():
        for stale in WEBP_CACHE.glob(f"{png.parent.name}--{png.stem}--*.webp"):
            stale.unlink()
        r = subprocess.run(["cwebp", "-quiet", "-lossless", "-z", "9", str(png), "-o", str(cached)],
                           capture_output=True)
        if r.returncode != 0 or not cached.exists():
            raise BuildError(f"cwebp failed on {png}: {r.stderr.decode().strip()}")
    return cached.read_bytes()


def placeholder_png(name):
    """A 4x3 grey PNG whose tEXt chunk marks it as a placeholder for `name`."""
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
    width, height = 4, 3
    raw = b"".join(b"\x00" + b"\x80\x80\x80" * width for _ in range(height))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"tEXt", PLACEHOLDER_MARK + b"\x00" + f"card 536 captures {name}".encode())
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


def make_placeholders(doc):
    made = []
    for step in doc["steps"]:
        for name in step["shots"]:
            for folder in SHOTS.values():
                target = folder / f"{name}.png"
                if not target.exists():
                    folder.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(placeholder_png(name))
                    made.append(f"{folder.name}/{name}.png")
    return made


# ---------------------------------------------------------------- comments

_GONE = "\x00"


def _tidy(text):
    """Drop lines a removed comment left empty; rstrip lines that held one."""
    out = []
    for line in text.split("\n"):
        if _GONE in line:
            line = line.replace(_GONE, "").rstrip()
            if not line.strip():
                continue
        out.append(line)
    return "\n".join(out)


def _string_end(text, i):
    quote = text[i]
    j = i + 1
    while j < len(text) and text[j] != quote:
        j += 2 if text[j] == "\\" else 1
    return j + 1


def strip_css(text):
    """CSS without its /* */ comments. Strings are kept as they are."""
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c in "\"'":
            j = _string_end(text, i)
            out.append(text[i:j])
            i = j
        elif text.startswith("/*", i):
            j = text.index("*/", i + 2) + 2
            out.append(_GONE + ("\n" + _GONE) * text.count("\n", i, j))
            i = j
        else:
            out.append(c)
            i += 1
    return _tidy("".join(out))


_REGEX_BEFORE = set("(,=:[!&|?{};+-*%<>~^") | {""}


def strip_js(text):
    """JavaScript without its comments. Strings, template literals and regex
    literals are kept; a regex literal is a slash after an operator or an
    opening bracket, which covers the two files this page inlines."""
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c in "\"'`":
            j = _string_end(text, i)
            out.append(text[i:j])
            i = j
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = len(text) if j < 0 else j
            out.append(_GONE)
            i = j
        elif text.startswith("/*", i):
            j = text.index("*/", i + 2) + 2
            out.append(_GONE + ("\n" + _GONE) * text.count("\n", i, j))
            i = j
        elif c == "/" and "".join(out).replace(_GONE, "").rstrip()[-1:] in _REGEX_BEFORE:
            j, in_class = i + 1, False
            while j < len(text) and (in_class or text[j] != "/"):
                if text[j] == "\\":
                    j += 1
                elif text[j] == "[":
                    in_class = True
                elif text[j] == "]":
                    in_class = False
                j += 1
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(c)
            i += 1
    return _tidy("".join(out))


def sync_site(website=None):
    """Write site/tokens.css and site/designs.js from the website, without comments."""
    website = website or WEBSITE
    if website is None or not (website / "tokens.css").is_file():
        raise BuildError(f"no folder with design/website above {REPO}; --sync-site needs the umbrella folder")
    for name, strip in (("tokens.css", strip_css), ("designs.js", strip_js)):
        (HERE / "site" / name).write_text(strip((website / name).read_text(encoding="utf-8")), encoding="utf-8")
    return [f"site/{n}" for n in ("tokens.css", "designs.js")]


# ---------------------------------------------------------------- stamp

def input_files(doc):
    """The files the page is built from. LocalSetupDriftTest.inputFiles applies the same rule."""
    files = {HERE / name for name in FIXED_INPUTS}
    for folder in INPUT_FOLDERS:
        for f in (HERE / folder).rglob("*"):
            if f.is_file() and not f.name.startswith("."):
                files.add(f)
    for step in doc["steps"]:
        if isinstance(step["script"], dict):
            for copy in step["script"]["copy"]:
                files.add(REPO / copy["from"])
    return sorted(files, key=lambda f: f.relative_to(REPO).as_posix())


def input_digest(doc):
    lines = "".join(f"{f.relative_to(REPO).as_posix()}\t{hashlib.sha256(f.read_bytes()).hexdigest()}\n"
                    for f in input_files(doc))
    return hashlib.sha256(lines.encode("utf-8")).hexdigest()


def stamp(page, doc):
    """Put the build stamp where render left its slot."""
    rest = page.replace(STAMP_SLOT, "", 1)
    line = STAMP_LINE.format(inputs=input_digest(doc), page=hashlib.sha256(rest.encode("utf-8")).hexdigest())
    return page.replace(STAMP_SLOT, line, 1)


# ---------------------------------------------------------------- render

def esc(text):
    return html.escape(text, quote=True)


def src_html(value):
    out = []
    for src in sources_of(value):
        if src.startswith("S"):
            out.append(f'<a href="#src-{src}">{src}</a>')
        else:
            path, _, needle = src[2:].partition("::")
            cite = f' <code>{esc(needle)}</code>' if needle else ""
            out.append(f'<a href="{esc(GITHUB_BLOB + path)}">{esc(path.rsplit("/", 1)[-1])}</a>{cite}')
    return ", ".join(out)


def needs_html(doc, names):
    if not names:
        return ""
    links = ", ".join(f'<a href="#needs-{n}">{esc(doc["page"]["needs"][n]["name"])}</a>' for n in names)
    return f'<p class="cmd-need">needs {links}</p>'


def command_html(doc, c, klass="cmd", button="copy"):
    label = f'<p class="cmd-label">{esc(c["label"])}</p>' if c.get("label") else ""
    return (f'<div class="cmdbox">{label}{needs_html(doc, c.get("needs", []))}<div class="cmd-row"><pre class="{klass}"><code>{esc(c["text"])}</code></pre>'
            f'<button type="button" class="{button}" aria-label="Copy this command">copy</button></div>'
            f'<p class="cmd-src">source {src_html(c["source"])}</p></div>')


def vendor_html(v):
    return (f'<div class="vendor"><p>{esc(v["says"])} <a href="{esc(v["url"])}">The vendor page</a>.</p>'
            f'<pre><code>{esc(v["text"])}</code></pre>'
            f'<p class="note-src">source {src_html(v["source"])}</p></div>')


def note_html(n):
    return f'<p class="note">{esc(n["text"])} <span class="note-src">({src_html(n["source"])})</span></p>'


def links_html(items):
    if not items:
        return ""
    lis = "".join(f'<li><a href="{esc(l["url"])}">{esc(l["label"])}</a> '
                  f'<span class="note-src">({src_html(l["source"])})</span></li>' for l in items)
    return f'<ul class="links">{lis}</ul>'


def check_html(check):
    if check["kind"] == "none":
        return f'<p class="check-text">{esc(check["text"])}</p>'
    expect = f'<p class="expect">{esc(check["expect"])}</p>' if check.get("expect") else ""
    if check["kind"] == "command":
        return (f'<div class="cmd-row"><pre class="cmd-check"><code>{esc(check["text"])}</code></pre>'
                f'<button type="button" class="copy-check" aria-label="Copy this check">copy</button></div>'
                f'{expect}<p class="cmd-src">source {src_html(check["source"])}</p>')
    return (f'<p class="check-text">{esc(check["text"])}</p>{expect}'
            f'<p class="cmd-src">source {src_html(check["source"])}</p>')


def plate_html(name, caption):
    pngs = {d: SHOTS[d] / f"{name}.png" for d in SHOTS}
    if any(is_placeholder(p) for p in pngs.values()):
        return (f'<figure class="plate"><div class="pending">Screenshot to come: {esc(name)}</div>'
                f'<figcaption>{esc(caption)}</figcaption></figure>')
    imgs = "".join(
        f'<img class="shot shot-{d}" data-shot="{esc(name)}" alt="{esc(caption)}" '
        f'src="data:image/webp;base64,{base64.b64encode(webp_bytes(pngs[d])).decode()}">'
        for d in ("dark", "light"))
    return f'<figure class="plate">{imgs}<figcaption>{esc(caption)}</figcaption></figure>'


def join_words(words):
    words = list(words)
    if len(words) <= 1:
        return "".join(words)
    return ", ".join(words[:-1]) + " and " + words[-1]


def card_html(doc, step, scripts):
    sid = step["id"]
    paths = doc["paths"]
    on = [paths[p] for p in paths if p in step["applies"]]
    off = [paths[p] for p in paths if p not in step["applies"]]
    chips = '<span class="chips-label">install paths</span>' + "".join(f'<span class="chip">{esc(p)}</span>' for p in on)
    if off:
        chips += '<span class="chips-label">not needed for</span>' + "".join(
            f'<span class="chip off">{esc(p)}</span>' for p in off)
    parts = [
        f'<article class="card" id="step-{sid}" data-step="{sid}" data-level="{step["level"]}">',
        f'<header class="card-head"><span class="card-id">{sid}</span><h3>{esc(step["title"])}</h3>'
        f'<label class="mark"><input type="checkbox" data-mark="{sid}"> I have this</label></header>',
        f'<p class="enables">{esc(step["enables"])}</p>',
        f'<p class="chips">{chips}</p>',
    ]
    if "notNeeded" in step:
        parts.append(f'<p class="not-needed">This step is not needed for the {esc(join_words(off))}. '
                     f'{esc(step["notNeeded"]["text"])} <span class="note-src">({src_html(step["notNeeded"]["source"])})</span></p>')

    has_platform_content = any(step.get(g, {}).get(p) for g in ("commands", "vendor", "links", "notes") for p in PLATFORMS)
    if has_platform_content or step["script"] is not None:
        for platform in PLATFORMS:
            name = doc["platformNames"][platform]
            body = []
            if platform not in step["platforms"]:
                body.append(f'<p class="none">This step is not covered on {name} yet.</p>')
            else:
                for v in step.get("vendor", {}).get(platform, []):
                    body.append(vendor_html(v))
                for c in step["commands"].get(platform, []):
                    body.append(command_html(doc, c))
                body.append(links_html(step.get("links", {}).get(platform, [])))
                for n in step.get("notes", {}).get(platform, []):
                    body.append(note_html(n))
                downloads = []
                if step["script"] == "generate" and platform in step["commands"]:
                    fname = script_name(sid, platform)
                    if fname in scripts:
                        downloads.append(fname)
                elif isinstance(step["script"], dict):
                    downloads += [c["to"] for c in step["script"]["copy"]]
                if downloads:
                    body.append('<p class="sub">script</p>' + "".join(
                        f'<a class="dl" href="scripts/{esc(f)}" download>{esc(f.rsplit("/", 1)[-1])}</a>' for f in downloads)
                        + f'<p class="scripts-note">{esc(doc["page"].get("scriptsNote", ""))}</p>')
                if not any(body):
                    body.append(f'<p class="none">Nothing to type on {name} for this step.</p>')
            parts.append(f'<div class="plat" data-platform="{platform}"><p class="sub">{name}</p>{"".join(body)}<!--/plat--></div>')

    parts.append(links_html(step.get("links", {}).get("all", [])))
    for n in step.get("notes", {}).get("all", []):
        parts.append(note_html(n))

    checks = step["check"]
    covered = [p for p in PLATFORMS if p in step["platforms"]]
    only = "" if len(covered) == len(PLATFORMS) else f' data-platform="{covered[0]}"'
    check_parts = [f'<div class="check"{only}><p class="sub">check</p>']
    if "all" in checks:
        check_parts.append(check_html(checks["all"]))
    for platform in PLATFORMS:
        if platform in checks:
            check_parts.append(f'<div data-platform="{platform}">{check_html(checks[platform])}</div>')
    check_parts.append("</div>")
    parts.append("".join(check_parts))

    for name in step["shots"]:
        parts.append(plate_html(name, doc["plates"][name]))
    for size in step["size"]:
        only = "" if set(size["platforms"]) == set(PLATFORMS) else f' data-platform="{size["platforms"][0]}"'
        parts.append(f'<p class="size"{only}>{esc(size["text"])} Measured {esc(size["date"])}, method: '
                     f'{esc(size["method"])} ({src_html(size["source"])}).</p>')
    parts.append("</article>")
    return "\n".join(p for p in parts if p)


def used_sources(doc, shown):
    found = set()

    def add(value):
        for s in sources_of(value):
            if s.startswith("S"):
                found.add(s)

    for step in shown:
        for cs in step["commands"].values():
            for c in cs:
                add(c["source"])
        for group in ("vendor", "notes", "links"):
            for items in step.get(group, {}).values():
                for item in items:
                    add(item["source"])
        for check in step["check"].values():
            if "source" in check:
                add(check["source"])
        for size in step["size"]:
            add(size["source"])
        for key in ("address", "notNeeded"):
            if key in step:
                add(step[key]["source"])
    if "scope" in doc["page"]:
        add(doc["page"]["scope"]["source"])
    for item in doc["page"].get("needs", {}).values():
        for entry in item["platforms"].values():
            add(entry["source"])
    return sorted(found, key=lambda s: int(s[1:]))


def inline_js(text):
    """A script inlined into <script>: a literal </script would end the element early.

    designs.js names its own tag in its header comment, so the parser would
    stop there and run half the file. The escape changes no JavaScript.
    """
    return text.replace("</script", "<\\/script")


def needs_block(doc):
    """The header's list of tools some lines need, one paragraph per tool and platform."""
    items = []
    for key, item in doc["page"].get("needs", {}).items():
        paras = []
        for platform in PLATFORMS:
            entry = item["platforms"].get(platform)
            if entry is None:
                continue
            links = [(entry["url"], entry["linkLabel"])] + [(m["url"], m["linkLabel"]) for m in entry.get("more", [])]
            anchors = join_words(f'<a href="{esc(u)}">{esc(label)}</a>' for u, label in links)
            paras.append(f'<p data-platform="{platform}"><strong>{esc(item["name"])}</strong> {esc(entry["text"])} '
                         f'{anchors} <span class="note-src">({src_html(entry["source"])})</span></p>')
        items.append(f'<div class="need" id="needs-{key}">{"".join(paras)}</div>')
    if not items:
        return ""
    return '<div class="needs"><p class="sub">before you start</p>' + "".join(items) + "</div>\n"


