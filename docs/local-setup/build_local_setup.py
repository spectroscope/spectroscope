#!/usr/bin/env python3
"""build_local_setup.py: builds docs/local-setup/index.html from steps.json (card 529).

Re-runnable generator. Never hand-edit the page or the scripts it writes:
    python3 docs/local-setup/build_local_setup.py
    python3 docs/local-setup/build_local_setup.py --date 2026-10-11   (fixed date)

Inputs, all in docs/local-setup/
  steps.json          levels, steps, commands per platform, checks, sources
  steps.schema.json   the shape of steps.json, checked before anything is written
  site/tokens.css     the website's design tokens: design/website/tokens.css
                      without its comments (--sync-site writes it)
  site/designs.js     the website's design switch, the same way
  page.css, page.js   this page's own layout and behaviour
  shots/, shots-light/  the plates as PNG masters, dark and paper design

Outputs
  docs/local-setup/index.html    one file: tokens, script and plates inline
  docs/local-setup/scripts/      the downloadable scripts: product scripts
                                 copied byte for byte, and one generated
                                 script per step and platform

Comments of the inlined CSS and JS are dropped, at --sync-site and again when
the page is built: they carry dashes and internal notes, the page needs code.

The page carries a build stamp, <meta name="spectroscope:build">: the sha256
of its inputs (input_files) and of the page itself without that line. The
Java LocalSetupDriftTest recomputes both, so CI sees a page that lags its
data or was edited by hand, without Python and without cwebp.

The page links its scripts as scripts/<name>. The tracked page sits where the
three places that serve it put it (the website, the jar, ~/.spectro):
local-setup/index.html with the scripts folder beside it, so the links resolve
in the tree as well as on the site.

Refusals. The build stops, and writes nothing, when steps.json breaks its
schema, when a command, note, link, check or size names no source, when an S
source is not in the sources table, when a P source names a file that does not
exist or a text that file does not hold (P:<path>::<text>, at most 48
characters), or when a plate named by a step is missing from shots/ or shots-light/.

Plates are embedded as lossless WebP like the user guide's (cwebp, cached in
.webp-cache/ on the PNG's mtime and size). A placeholder plate (a PNG carrying
the tEXt keyword spectroscope-placeholder) is shown as a marked box instead.
Card 536 replaces the placeholders with captures.

The date in the footer and in the script headers is --date, else
SOURCE_DATE_EPOCH, else today in UTC, so a rebuild with the same date is byte
identical.

The footer prints page.version from steps.json, never the version in the
build files. tag.yml bumps the build files and then greps the tree for the old
version, and it cannot rebuild this page; so the release preparation sets
page.version and rebuilds, as it does for README.md.

The website, the private scan list and the research live in the umbrella
folder above the product repository. find_umbrella walks up from the
repository to the first folder that holds design/website, which works from
the main checkout and from a worktree; in CI there is none.
"""

